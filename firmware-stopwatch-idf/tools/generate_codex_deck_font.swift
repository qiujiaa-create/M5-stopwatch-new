// Small, reproducible Chinese-only LVGL font. ASCII falls back to Montserrat 16.
// Run from firmware-stopwatch-idf: swift tools/generate_codex_deck_font.swift
import Foundation
import CoreGraphics
import CoreText

let text = "旋钮左右滑动执行中未读待处理异常离线未知状态长按秒确认四向控制"
let scalars = Array(Set(text.unicodeScalars.map { $0.value })).sorted()
let size = 16, width = 18, height = 22
let font = CTFontCreateWithName("PingFangSC-Semibold" as CFString, CGFloat(size), nil)
var bitmap: [UInt8] = []
var descriptors = ["    {0, 0, 0, 0, 0, 0},"]
for scalar in scalars {
    var pixels = [UInt8](repeating: 0, count: width * height)
    pixels.withUnsafeMutableBytes { buffer in
        let context = CGContext(data: buffer.baseAddress, width: width, height: height,
                                bitsPerComponent: 8, bytesPerRow: width,
                                space: CGColorSpaceCreateDeviceGray(), bitmapInfo: 0)!
        context.setFillColor(gray: 0, alpha: 1)
        context.fill(CGRect(x: 0, y: 0, width: width, height: height))
        let attrs: [CFString: Any] = [kCTFontAttributeName: font,
                                     kCTForegroundColorAttributeName: CGColor(gray: 1, alpha: 1)]
        let string = String(UnicodeScalar(scalar)!)
        let line = CTLineCreateWithAttributedString(CFAttributedStringCreate(nil, string as CFString, attrs as CFDictionary)!)
        context.textPosition = CGPoint(x: 1, y: 5)
        CTLineDraw(line, context)
    }
    descriptors.append("    {\(bitmap.count), \(size * 16), \(width), \(height), 0, -5},")
    for index in stride(from: 0, to: pixels.count, by: 2) {
        bitmap.append((pixels[index] & 0xf0) | (pixels[index + 1] >> 4))
    }
}
let bytes = stride(from: 0, to: bitmap.count, by: 16).map { start in
    "    " + bitmap[start..<min(start + 16, bitmap.count)].map { String(format: "0x%02x", $0) }.joined(separator: ", ") + ","
}.joined(separator: "\n")
let first = scalars.first!, last = scalars.last!
let unicodeList = scalars.map { String(format: "0x%x", $0 - first) }.joined(separator: ", ")
let source = """
// Generated by tools/generate_codex_deck_font.swift. Do not edit bitmap data.
#include <lvgl.h>
static const uint8_t glyph_bitmap[] = {
\(bytes)
};
static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {
\(descriptors.joined(separator: "\n"))
};
static const uint16_t unicode_list[] = {\(unicodeList)};
static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    .range_start = \(first), .range_length = \(last - first + 1), .glyph_id_start = 1,
    .unicode_list = unicode_list, .glyph_id_ofs_list = NULL, .list_length = \(scalars.count),
    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
}};
static lv_font_fmt_txt_dsc_t font_dsc = {
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4, .kern_classes = 0, .bitmap_format = 0,
};
const lv_font_t codex_deck_16 = {
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = 22, .base_line = 5, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -2, .underline_thickness = 1, .dsc = &font_dsc,
    .fallback = &lv_font_montserrat_16,
};

"""
try source.write(toFile: "main/assets/fonts/codex_deck_16.c", atomically: true, encoding: .utf8)
print("Generated codex_deck_16: \(scalars.count) glyphs, \(bitmap.count) bitmap bytes")
